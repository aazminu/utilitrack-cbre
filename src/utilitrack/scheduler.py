"""SLA-constrained facility maintenance technician work-order dispatch engine.

Optimizes technician assignment across CBRE commercial property portfolios by balancing
SLA urgency, trade skill qualification, travel ETA, active workload, and parasitic
energy waste mitigation (kW).
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Sequence

SEVERITY_WEIGHTS: dict[str, float] = {
    "CRITICAL": 100.0,
    "HIGH": 65.0,
    "MEDIUM": 35.0,
    "LOW": 15.0,
}


@dataclass(frozen=True)
class WorkOrder:
    """Facility maintenance work order generated by BMS fault detection or tenant ticket."""

    order_id: str
    asset_id: str
    required_skill: str
    severity: str
    sla_hours_remaining: float
    location_xy: tuple[float, float]
    estimated_duration_hours: float
    est_energy_waste_kw: float = 0.0

    def __post_init__(self) -> None:
        if self.severity.upper() not in SEVERITY_WEIGHTS:
            raise ValueError(f"Invalid severity: {self.severity}")
        if self.estimated_duration_hours <= 0:
            raise ValueError("estimated_duration_hours must be positive.")
        if self.est_energy_waste_kw < 0:
            raise ValueError("est_energy_waste_kw cannot be negative.")


@dataclass(frozen=True)
class Technician:
    """Field facility engineer / HVAC technician available for work-order dispatch."""

    tech_id: str
    name: str
    skills: frozenset[str]
    current_xy: tuple[float, float]
    available_hours: float
    active_workload_hours: float = 0.0
    hourly_rate_usd: float = 85.0


@dataclass(frozen=True)
class DispatchAssignment:
    """Matched assignment between a facility work order and a qualified technician."""

    order_id: str
    tech_id: str
    priority_score: float
    dispatch_cost_score: float
    travel_distance_km: float
    travel_eta_minutes: float
    sla_compliant: bool


@dataclass(frozen=True)
class SchedulePlan:
    """Portfolio-wide maintenance dispatch schedule summary."""

    assignments: list[DispatchAssignment]
    unassigned_order_ids: list[str]
    total_energy_waste_mitigated_kw: float
    sla_compliance_rate: float


def euclidean_distance_km(p1: tuple[float, float], p2: tuple[float, float]) -> float:
    """Compute planar Euclidean distance in kilometers between two campus/metro coordinates."""
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])


def compute_work_order_priority(order: WorkOrder) -> float:
    """Compute composite priority score for ordering maintenance dispatch.

    Combines base severity weight, hyperbolic SLA time-to-breach urgency, and continuous
    HVAC/electrical energy waste penalty (kW).
    """
    sev_weight = SEVERITY_WEIGHTS[order.severity.upper()]
    clamped_sla = max(0.25, order.sla_hours_remaining)
    sla_urgency = 40.0 / clamped_sla
    energy_bonus = 1.75 * order.est_energy_waste_kw
    return sev_weight + sla_urgency + energy_bonus


def dispatch_work_orders(
    orders: Sequence[WorkOrder],
    technicians: Sequence[Technician],
    avg_speed_kmh: float = 40.0,
) -> SchedulePlan:
    """Assign prioritized facility work orders to qualified field technicians.

    Work orders are ranked in descending order of `compute_work_order_priority`.
    For each work order, candidate technicians possessing `required_skill` and enough
    remaining shift hours (`available_hours >= travel_hours + estimated_duration_hours`)
    are evaluated on a composite dispatch cost combining travel distance, existing
    workload imbalance, labor cost, and SLA breach penalty.
    """
    if avg_speed_kmh <= 0:
        raise ValueError("avg_speed_kmh must be positive.")

    if not orders:
        return SchedulePlan(
            assignments=[],
            unassigned_order_ids=[],
            total_energy_waste_mitigated_kw=0.0,
            sla_compliance_rate=1.0,
        )

    # Track mutable technician state across sequential assignments
    tech_state: dict[str, dict[str, object]] = {
        t.tech_id: {
            "tech": t,
            "xy": t.current_xy,
            "rem_hours": t.available_hours,
            "workload": t.active_workload_hours,
        }
        for t in technicians
    }

    ranked_orders = sorted(orders, key=compute_work_order_priority, reverse=True)

    assignments: list[DispatchAssignment] = []
    unassigned: list[str] = []
    mitigated_kw = 0.0

    for order in ranked_orders:
        prio = compute_work_order_priority(order)
        req_skill = order.required_skill.lower()

        best_tech_id: str | None = None
        best_cost = float("inf")
        best_dist = 0.0
        best_eta_min = 0.0
        best_sla_ok = False

        for tid, state in tech_state.items():
            tech: Technician = state["tech"]  # type: ignore[assignment]
            curr_xy: tuple[float, float] = state["xy"]  # type: ignore[assignment]
            rem_hours: float = state["rem_hours"]  # type: ignore[assignment]
            workload: float = state["workload"]  # type: ignore[assignment]

            normalized_skills = {s.lower() for s in tech.skills}
            if req_skill not in normalized_skills:
                continue

            dist_km = euclidean_distance_km(curr_xy, order.location_xy)
            travel_hours = dist_km / avg_speed_kmh
            total_job_hours = travel_hours + order.estimated_duration_hours

            if rem_hours < total_job_hours:
                continue

            # SLA compliance check: technician arrives before SLA window expires
            sla_ok = travel_hours <= max(0.0, order.sla_hours_remaining)
            sla_penalty = 0.0 if sla_ok else 250.0

            # Composite cost: travel distance + workload balancing + rate normalization + SLA breach
            cost = (
                2.5 * dist_km
                + 4.0 * workload
                + 0.15 * tech.hourly_rate_usd
                + sla_penalty
            )

            if cost < best_cost:
                best_cost = cost
                best_tech_id = tid
                best_dist = dist_km
                best_eta_min = travel_hours * 60.0
                best_sla_ok = sla_ok

        if best_tech_id is not None:
            chosen = tech_state[best_tech_id]
            travel_hours = best_eta_min / 60.0
            chosen["xy"] = order.location_xy
            chosen["rem_hours"] = float(chosen["rem_hours"]) - (  # type: ignore[arg-type]
                travel_hours + order.estimated_duration_hours
            )
            chosen["workload"] = float(chosen["workload"]) + (  # type: ignore[arg-type]
                travel_hours + order.estimated_duration_hours
            )

            assignments.append(
                DispatchAssignment(
                    order_id=order.order_id,
                    tech_id=best_tech_id,
                    priority_score=prio,
                    dispatch_cost_score=best_cost,
                    travel_distance_km=best_dist,
                    travel_eta_minutes=best_eta_min,
                    sla_compliant=best_sla_ok,
                )
            )
            mitigated_kw += order.est_energy_waste_kw
        else:
            unassigned.append(order.order_id)

    compliant_count = sum(1 for a in assignments if a.sla_compliant)
    sla_rate = compliant_count / len(orders) if orders else 1.0

    return SchedulePlan(
        assignments=assignments,
        unassigned_order_ids=unassigned,
        total_energy_waste_mitigated_kw=mitigated_kw,
        sla_compliance_rate=sla_rate,
    )
